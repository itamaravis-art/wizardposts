/* ------------------------------------------------------------------ */
/* Pages — Facebook Pages connected via Graph API.                    */
/*                                                                    */
/* The einatural module: a user owns a real FB Page and grants us a   */
/* long-lived Page Access Token. We then publish AI-generated posts   */
/* directly via Graph API (no Worker / Playwright needed for this     */
/* surface — the user owns the Page so Development Mode is enough).   */
/*                                                                    */
/* The token is stored encrypted (AES-256-GCM via lib/crypto.ts);     */
/* never read it raw outside the decrypt() helper.                    */
/*                                                                    */
/* brand_kit holds tone, audience, pillars, hashtags, image style and */
/* publish slots — used by the AI generation cron to keep voice       */
/* consistent across posts. Schema-less jsonb so we can iterate the   */
/* shape without migrations.                                          */
/* ------------------------------------------------------------------ */

export const pages = pgTable(
  'pages',
  {
    id: uuid('id').primaryKey().default(sql`gen_random_uuid()`),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    fbPageId: text('fb_page_id').notNull(),
    pageName: text('page_name').notNull(),
    accessToken: text('access_token').notNull(), // AES-256-GCM ciphertext
    tokenExpiresAt: timestamp('token_expires_at', { withTimezone: true }),
    brandKit: jsonb('brand_kit').notNull(),
    active: boolean('active').notNull().default(true),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => ({
    userIdx: index('pages_user_id_idx').on(t.userId),
    activeIdx: index('pages_active_idx').on(t.active),
  }),
);

