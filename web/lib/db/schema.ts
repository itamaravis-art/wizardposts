export const posts = pgTable(
  'posts',
  {
    id: uuid('id').primaryKey().default(sql`gen_random_uuid()`),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    text: text('text').notNull(),
    imageUrl: text('image_url'),
    /**
     * Optional short video to attach to the post. mp4/webm/mov, up to
     * the upload route's size cap. When set, the worker uploads it via
     * the same Photo/Video composer button as images; FB accepts either.
     * imageUrl takes precedence if both are set.
     */
    videoUrl: text('video_url'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),

    // ---- Page-channel additions (Phase 1, einatural module) -----------
    // All new columns are nullable / have defaults so existing rows are
    // untouched and the existing 'group' code path keeps working.
    channel: channelEnum('channel').notNull().default('group'),
    // FK constraint added in the migration script (avoiding forward-ref
    // here because `pages` is declared after `posts` in this file).
    pageId: uuid('page_id'),
    imagePrompt: text('image_prompt'),
    captionVariants: jsonb('caption_variants'), // string[] generated by AI
    approvalStatus: text('approval_status'),
    // valid values for page-channel posts:
    //   'pending'   — awaiting human approval in /page/queue
    //   'approved'  — approved, queued for publish at scheduledAt
    //   'rejected'  — owner rejected, won't publish
    //   'skipped'   — passed the 09:30 cutoff without approval
    //   'published' — successfully posted to FB Page
    //   'failed'    — publisher gave up after 3 retries
    // Null for group-channel posts (they use the jobs table for status).
    approvedAt: timestamp('approved_at', { withTimezone: true }),
    scheduledAt: timestamp('scheduled_at', { withTimezone: true }),
    fbPostId: text('fb_post_id'),
    retryCount: integer('retry_count').notNull().default(0),
  },
  (t) => ({
    userIdx: index('posts_user_id_idx').on(t.userId),
    // Drives the publisher cron (every 5 min): pick approved posts whose
    // scheduledAt has passed and that haven't been published yet. Also
    // serves the queue UI's pending-list query.
    publishLookupIdx: index('posts_publish_lookup_idx').on(
      t.channel,
      t.approvalStatus,
      t.scheduledAt,
    ),
  }),
);

