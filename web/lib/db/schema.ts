/* Enums                                                              */
/* ------------------------------------------------------------------ */

export const campaignStatusEnum = pgEnum('campaign_status', [
  'draft',
  'running',
  'paused',
  'done',
  'cancelled',
  'error',
]);

export const jobStatusEnum = pgEnum('job_status', [
  'pending',
  'running',
  'success',
  'failed',
  'skipped',
]);

export const logLevelEnum = pgEnum('log_level', ['info', 'warn', 'error']);

/**
 * Channel for a post: which kind of FB surface it targets.
 * - 'group' — posted to a Facebook group (the original WizardPosts flow,
 *   driven by the local Playwright Worker via /api/worker/next-job).
 * - 'page'  — posted to a Facebook Page the user owns, via the Graph
 *   API. Generated by AI on a schedule, requires manual approval before
 *   publish.
 * Default 'group' so all pre-existing rows keep their semantics.
 */
export const channelEnum = pgEnum('channel', ['group', 'page']);

